_LANGUAGES: dict[str, dict[str, str]] = {"en": EN}
_current: dict[str, str] = EN


def set_language(code: str) -> None:
    global _current
    _current = _LANGUAGES.get(code, EN)


def tr(key: str, **kwargs: object) -> str:
    text = _current.get(key) or EN.get(key) or key
    return text.format(**kwargs) if kwargs else text


def format_date(value: "date | datetime | str", with_time: bool = False) -> str:
    """Locale-independent date text, e.g. ``15 Oct 2026`` (month names come from the strings)."""
    if isinstance(value, str):
        value = datetime.fromisoformat(value)
    month = tr("date.months").split()[value.month - 1]
    text = f"{value.day:02d} {month} {value.year}"
    if with_time and isinstance(value, datetime):
        text += f" {value:%H:%M}"
    return text
